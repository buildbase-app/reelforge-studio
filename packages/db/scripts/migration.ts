/**
 * Create a migration for every provider from the change in prisma/base.prisma.
 *
 *   pnpm --filter @reelforge/db migration <name>   write migrations/<provider>/<NNNN>_<name>/migration.sql
 *   pnpm --filter @reelforge/db migration --check  fail if the schema changed without a migration
 *
 * How: migrations/<provider>/schema.prisma is a snapshot of the schema at the
 * last migration. The new migration is `prisma migrate diff` from that
 * snapshot to the current generated schema (no database needed), so all three
 * providers get a migration with the same id. src/generated/migrations.ts
 * embeds the SQL so a bundled build needs no files next to it.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROVIDERS, type Provider } from '../src/schema-source';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** The Prisma CLI is developer tooling: run on demand, never installed with the app (keeps it out of the image). */
export const PRISMA_CLI = ['dlx', 'prisma@7.10.1'];
const args = process.argv.slice(2);
const check = args.includes('--check');
const name = args.find((a) => !a.startsWith('--'));

function diff(provider: Provider): string {
  const snapshot = join(root, 'migrations', provider, 'schema.prisma');
  const from = existsSync(snapshot) ? ['--from-schema', snapshot] : ['--from-empty'];
  const r = spawnSync('pnpm', [...PRISMA_CLI, 'migrate', 'diff', ...from, '--to-schema', join(root, 'prisma', provider, 'schema.prisma'), '--script'], {
    cwd: root,
    env: { ...process.env, PRISMA_PROVIDER: provider, CHECKPOINT_DISABLE: '1', PRISMA_HIDE_UPDATE_MESSAGE: '1' },
    encoding: 'utf8',
  });
  if (r.status !== 0) throw new Error(`prisma migrate diff failed for ${provider}:\n${r.stderr}`);
  const sql = r.stdout.trim();
  return /^-- This is an empty migration\.?$/.test(sql) ? '' : sql;
}

function migrationIds(provider: Provider): string[] {
  const dir = join(root, 'migrations', provider);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((d) => /^\d{4}_[a-z0-9_]+$/.test(d)).sort();
}

export function writeEmbedded() {
  const lines = [
    '// GENERATED by scripts/migration.ts from migrations/<provider>/*/migration.sql. Do not edit.',
    "import type { Migration } from '../migrate';",
    '',
    'export const MIGRATIONS: Record<string, Migration[]> = {',
  ];
  for (const p of PROVIDERS) {
    lines.push(`  ${p}: [`);
    for (const id of migrationIds(p)) {
      const sql = readFileSync(join(root, 'migrations', p, id, 'migration.sql'), 'utf8');
      lines.push(`    { id: ${JSON.stringify(id)}, sql: ${JSON.stringify(sql)} },`);
    }
    lines.push('  ],');
  }
  lines.push('};', '');
  const file = join(root, 'src/generated/migrations.ts');
  mkdirSync(dirname(file), { recursive: true });
  const next = lines.join('\n');
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current !== next) {
    if (check) throw new Error('src/generated/migrations.ts is out of date; run pnpm --filter @reelforge/db migration --embed');
    writeFileSync(file, next);
    console.log(`wrote ${file}`);
  }
}

const pending = PROVIDERS.map((p) => [p, diff(p)] as const).filter(([, sql]) => sql);
const ids = PROVIDERS.map((p) => migrationIds(p).join(','));
if (new Set(ids).size !== 1) throw new Error(`providers have different migrations: ${PROVIDERS.map((p, i) => `${p}=[${ids[i]}]`).join(' ')}`);

if (check) {
  if (pending.length) {
    console.error(`schema changed without a migration for: ${pending.map(([p]) => p).join(', ')}; run pnpm --filter @reelforge/db migration <name>`);
    process.exit(1);
  }
  writeEmbedded();
  console.log('migrations are up to date');
} else if (args.includes('--embed')) {
  writeEmbedded();
} else {
  if (!pending.length) {
    console.log('no schema changes; nothing to do');
    writeEmbedded();
    process.exit(0);
  }
  if (!name || !/^[a-z0-9_]+$/.test(name)) throw new Error('usage: migration <name> (lowercase letters, digits, _)');
  const next = String(migrationIds('sqlite').length + 1).padStart(4, '0');
  const id = `${next}_${name}`;
  for (const p of PROVIDERS) {
    const sql = diff(p);
    const dir = join(root, 'migrations', p, id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'migration.sql'), (sql || '-- no change for this provider') + '\n');
    copyFileSync(join(root, 'prisma', p, 'schema.prisma'), join(root, 'migrations', p, 'schema.prisma'));
    console.log(`wrote migrations/${p}/${id}/migration.sql`);
  }
  writeEmbedded();
}
