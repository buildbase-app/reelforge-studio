// Guards the rename (#408, phase 6 #415): the docs say RenderWeld, and the old
// public names stay only where they are history, a record, or a name the code
// still reads. Run: pnpm test:docs (node --test, no dependencies).
//
// A line fails when it uses, outside the allowed places:
// - the product name ReelForge (or REELFORGE as a word);
// - an old URL (reelforge.buildbase.app, reelforge-dev.buildbase.app);
// - an old MCP resource (reelforge://), CLI call (reelforge keys ...), OAuth
//   scope (reelforge:read ...), metric or label (reelforge_*) or trace
//   attribute (reelforge.job.id ...);
// - a REELFORGE_* variable that has a RENDERWELD_* twin, unless docker compose
//   reads it under that name (docker-compose.yml interpolates REELFORGE_*);
// - "Render Weld", "Renderweld", or "open source" said of RenderWeld.
//
// Lowercase identifiers that are data or deployment identity (the
// `reelforge-data` volume, database users, Kubernetes objects, file paths, the
// repository and image names until the GitHub rename, #409) are not public
// product names and are not checked.
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (path) => readFileSync(join(root, path), 'utf8');

/** Files and folders the guard reads. */
const ROOTS = ['README.md', 'SECURITY.md', 'SUPPORT.md', 'CODE_OF_CONDUCT.md', 'docs', 'examples', 'deployment'];

/** Kept as written, with the reason. */
const SKIP = [
  [/^docs\/RENAMED\.md$|^docs\/public\/install\/renamed-from-reelforge\.md$/, 'the rename pages list the old names on purpose'],
  [/^docs\/DECISIONS\.md$|^docs\/STATUS\.md$|^docs\/research\/|^CHANGELOG/, 'history: a note at the top says the product is now RenderWeld'],
  [/^docs\/CONFIG\.md$/, 'generated; lists every old variable as an alias of its new name'],
  [/^docs\/tutorials\//, 'generated from recorded proofs, which used the old MCP entry name; they move when proved again (pnpm tutorials:prove)'],
  [/^docs\/public\/screenshots\/|^docs\/public\/walkthroughs\.md$|^docs\/public\/install\/buildbase-console-setup\.md$/, 'generated by pnpm capture from the live store; they change with the next capture'],
];

/** Lines that explain the rename itself. */
const NOTE_LINE = /old names?|formerly|renamed from reelforge|renamed-from-reelforge|is now renderweld|is now \*\*renderweld|reelforge is now|reelforge was renamed|replaces reelforge|\balias|deprecat|insufficient_scope|both names|old uri|old token|old value|old label/i;

/** REELFORGE_* names with a RENDERWELD_* twin: every old name docs/CONFIG.md lists. */
const RENAMED = new Set([...read('docs/CONFIG.md').matchAll(/\bREELFORGE_[A-Z0-9_]*[A-Z0-9]\b/g)].map((m) => m[0].replace(/_FILE$/, '')));

/** REELFORGE_* names docker compose interpolates, so its docs keep them. */
const COMPOSE_FILES = ['docker-compose.yml', 'deployment/compose/docker-compose.scale.yml', 'deployment/compose/docker-compose.pgbouncer.yml', 'scripts/dev/compose.yml'];
const COMPOSE = new Set(COMPOSE_FILES.flatMap((f) => [...read(f).matchAll(/\$\{(REELFORGE_[A-Z0-9_]+)/g)].map((m) => m[1])));

/** The old site, reelforge(-dev).buildbase.app (renderweld.com and dev.renderweld.com now); matched without the TLD. */
const OLD_SITE = /\breelforge(?:-dev)?\.buildbase\b/;

const CLI = '(?:audit|backup|config|import-v01|keys|licence|license|migrate|storage|webhooks|worker|workspaces)';
const ATTR = '(?:job|jobs|render|queue|webhook|limits|licence|server|provider|build|key_id|request_id|project|engine|workspace)';

/** [rule, test(line) -> offending text or null]. */
const RULES = [
  ['product name', (l) => l.match(/\bReelForge\b|\bREELFORGE\b(?!_)/)?.[0]],
  ['old URL', (l) => l.match(OLD_SITE)?.[0]],
  ['old MCP resource', (l) => l.match(/\breelforge:\/\/\S*/)?.[0]],
  ['old CLI name', (l) => l.match(new RegExp(`(?:^|[\\s\`(]|pnpm )reelforge ${CLI}\\b`))?.[0]?.trim()],
  ['old OAuth scope', (l) => l.match(/\breelforge:(?:read|write|render|admin|owner)\b/)?.[0]],
  ['old metric or label', (l) => l.match(/\breelforge_(?!migrations\b|data\b)[a-z][a-z0-9_]*/)?.[0]],
  ['old trace attribute', (l) => l.match(new RegExp(`\\breelforge\\.${ATTR}\\b[\\w.]*`))?.[0]],
  [
    'old variable name',
    (l) => [...l.matchAll(/\bREELFORGE_[A-Z0-9_]*[A-Z0-9]\b/g)].map((m) => m[0]).find((n) => RENAMED.has(n.replace(/_FILE$/, '')) && !COMPOSE.has(n.replace(/_FILE$/, ''))),
  ],
  ['misspelt name', (l) => l.replace(/~~[^~]*~~/g, '').match(/\bRender[ -]Weld\b|\bRenderweld\b|\bRENDERWELD\b(?!_)/)?.[0]],
  [
    '"open source" said of RenderWeld (it is source-available)',
    (l) =>
      /open[- ]source/i.test(l) && /RenderWeld|\bwe\b|\bour\b|\bit is\b|\bit's\b/i.test(l) && !/\bnot\b|\bnever\b|isn't|source-available|["“]open[- ]source["”]/i.test(l)
        ? 'open source'
        : null,
  ],
];

/** The brand rules list the wrong spellings on purpose. */
const SPELLING_RULES = /^docs\/BRAND_AND_PRODUCTION\.md$|^docs\/brand\//;

/** Every offending line of one file's text: "path:line: rule: text". */
export function findOldNames(path, text) {
  const out = [];
  text.split('\n').forEach((line, i) => {
    if (NOTE_LINE.test(line)) return;
    for (const [rule, test] of RULES) {
      if (rule === 'misspelt name' && SPELLING_RULES.test(path)) continue;
      const hit = test(line);
      if (hit) out.push(`${path}:${i + 1}: ${rule}: ${hit}`);
    }
  });
  return out;
}

function files(path) {
  if (statSync(join(root, path)).isDirectory()) return readdirSync(join(root, path)).flatMap((f) => files(`${path}/${f}`));
  return /\.(md|mdx)$/.test(path) || path === 'docs/public/manifest.json' ? [path] : [];
}

const PAGES = ROOTS.flatMap(files).filter((p) => !SKIP.some(([rx]) => rx.test(p)));

describe('the docs say RenderWeld (#415)', () => {
  it('reads the inputs', () => {
    assert.ok(PAGES.length > 60, `only ${PAGES.length} pages`);
    assert.ok(RENAMED.size > 150, `only ${RENAMED.size} renamed variables read from docs/CONFIG.md`);
    assert.ok(COMPOSE.has('REELFORGE_SECRET_KEY'), 'docker-compose.yml no longer reads REELFORGE_SECRET_KEY: update COMPOSE');
  });

  it('no old public name outside the rename pages, records and generated captures', () => {
    const hits = PAGES.flatMap((p) => findOldNames(p, read(p)));
    assert.deepEqual(hits, [], `old names (use the RenderWeld name, or explain the rename on that line):\n${hits.join('\n')}`);
  });

  it('records keep their wording and say so at the top', () => {
    for (const p of ['docs/DECISIONS.md', 'docs/STATUS.md', ...readdirSync(join(root, 'docs/research')).map((f) => `docs/research/${f}`)]) {
      if (!p.endsWith('.md')) continue;
      const head = read(p).split('\n').slice(0, 12).join('\n');
      assert.match(head, /ReelForge is now RenderWeld|now called RenderWeld/, `${p}: add the rename note at the top`);
    }
  });

  it('catches each kind of old name', () => {
    const bad = [
      'ReelForge renders reels.',
      'See https://reelforge.buildbase.app/pricing.',
      'Read reelforge://guide/workflow first.',
      'Run `reelforge keys create`.',
      'pnpm reelforge migrate',
      'A token with reelforge:render.',
      'Alert on reelforge_jobs_queued.',
      'Filter on reelforge.job.id.',
      'Set REELFORGE_RENDER_ENCODER_THREADS=2.',
      'Never write Render Weld.',
      'RenderWeld is open source.',
    ];
    for (const line of bad) assert.equal(findOldNames('x.md', line).length, 1, `not caught: ${line}`);
    const fine = [
      'RenderWeld renders reels.',
      'docker compose exec reelforge renderweld keys create',
      'echo "REELFORGE_SECRET_KEY=$(openssl rand -base64 32)" >> .env',
      'Back up the `reelforge-data` volume.',
      'REELFORGE_RENDER_CONCURRENCY is the old name of RENDERWELD_RENDER_CONCURRENCY.',
      'RenderWeld is source-available, not open source.',
      'Never split: ~~Render Weld~~',
      'git clone https://github.com/buildbase-app/reelforge-studio.git',
    ];
    for (const line of fine) assert.deepEqual(findOldNames('x.md', line), [], `flagged: ${line}`);
  });
});
