/** Files whose content differs from what the code generates. */
export function staleOutputs(): string[] {
  return OUTPUTS.filter(({ path, render }) => {
    let current = '';
    try {
      current = readFileSync(join(root, path), 'utf8');
    } catch {
      return true;
    }
    return current !== render();
  }).map((o) => o.path);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  if (process.argv.includes('--check')) {
    const stale = staleOutputs();
    if (stale.length) {
      console.error(`Out of date: ${stale.join(', ')}. Run \`pnpm docs:reference\`.`);
      process.exit(1);
    }
    console.log('Generated docs are up to date.');
  } else {
    for (const { path, render } of OUTPUTS) {
      writeFileSync(join(root, path), render());
      console.log(`wrote ${path}`);
    }
  }
}
