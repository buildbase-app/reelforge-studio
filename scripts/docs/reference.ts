// Markdown table cell: escape backslashes first, then pipes; one line.
const cell = (s: string) =>
  s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();

function frontMatter(fields: Record<string, string | number | string[]>): string {
  const lines = Object.entries(fields).map(([k, v]) => {
    if (Array.isArray(v)) return `${k}: [${v.join(', ')}]`;
    if (typeof v === 'number') return `${k}: ${v}`;
    return `${k}: ${JSON.stringify(v)}`;
  });
  return ['---', ...lines, '---', ''].join('\n');
}

type JsonSchema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  items?: JsonSchema;
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
};

function typeOf(s: JsonSchema): string {
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (s.const !== undefined) return JSON.stringify(s.const);
  const alts = s.anyOf ?? s.oneOf;
  if (alts) return [...new Set(alts.map(typeOf))].join(' \\| ');
  if (s.type === 'array') {
    const item = s.items ? typeOf(s.items) : 'any';
    return item.includes('|') ? `(${item})[]` : `${item}[]`;
  }
  if (Array.isArray(s.type)) return s.type.join(' \\| ');
  return s.type ?? 'any';
}

/** One tool's inputs as a Markdown table, from its Zod shape. */
function inputTable(shape: Record<string, z.ZodType>): string {
  const json = z.toJSONSchema(z.object(shape), { io: 'input', unrepresentable: 'any' }) as JsonSchema;
  const props = Object.entries(json.properties ?? {});
  if (props.length === 0) return 'No arguments.';
  const required = new Set(json.required ?? []);
  const rows = props.map(([name, s]) => {
    const desc = s.description ?? (s.anyOf ?? []).map((a) => a.description).find(Boolean) ?? '';
    return `| \`${name}\` | ${typeOf(s)} | ${required.has(name) ? 'yes' : 'no'} | ${cell(desc)} |`;
  });
  return ['| Argument | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows].join('\n');
}

function hints(a: (typeof TOOLS)[number]['annotations']): string {
  const out: string[] = [];
  if (a?.readOnlyHint) out.push('read-only');
  if (a?.destructiveHint) out.push('destructive');
  if (a?.idempotentHint) out.push('idempotent');
  return out.length ? `, ${out.join(', ')}` : '';
}

/** The REST route(s) that offer the same capability as a tool. */
function restFor(tool: string): string[] {
  const routes = REST_ROUTES.filter((r) => r.tool === tool).map((r) => `\`${r.method} ${r.display ?? r.path}\``);
  if (TOOL_ALIASES[tool]) routes.push(`\`${TOOL_ALIASES[tool]}\``);
  return routes;
}

export function renderToolsDoc(): string {
  const byName = new Map(TOOLS.map((t) => [t.name, t]));
  const grouped = TOOL_GROUPS.flatMap((g) => g.tools);
  const unknown = grouped.filter((n) => !byName.has(n));
  const missing = TOOLS.map((t) => t.name).filter((n) => !grouped.includes(n));
  const dupes = grouped.filter((n, i) => grouped.indexOf(n) !== i);
  if (unknown.length || missing.length || dupes.length) {
    throw new Error(
      `TOOL_GROUPS in scripts/docs/reference.ts is out of date: ` +
        [
          missing.length ? `not grouped: ${missing.join(', ')}` : '',
          unknown.length ? `no such tool: ${unknown.join(', ')}` : '',
          dupes.length ? `listed twice: ${dupes.join(', ')}` : '',
        ]
          .filter(Boolean)
          .join('; ')
    );
  }

  const out: string[] = [
    frontMatter({
      title: 'MCP tool reference',
      description: `All ${TOOLS.length} MCP tools of RenderWeld, grouped by task, with their scopes, arguments and REST equivalents.`,
      folder: 'mcp',
      slug: 'tools',
      order: 2,
      tags: ['mcp', 'reference'],
    }),
    '# MCP tool reference',
    '',
    GENERATED,
    '',
    `RenderWeld offers **${TOOLS.length} tools** at \`/mcp\`, generated here from the server's tool registry.`,
    'Every tool has a REST equivalent under `/v1` with the same scope. Tool names are **experimental until v1.0**.',
    'Errors come back as a tool result with `isError: true` and `{ "error": { "code", "message", "details" } }`.',
    '',
    '| Group | Tools |',
    '| --- | --- |',
    ...TOOL_GROUPS.map((g) => `| ${g.title} | ${g.tools.map((n) => `\`${n}\``).join(', ')} |`),
    '',
  ];
  for (const g of TOOL_GROUPS) {
    out.push(`## ${g.title}`, '', g.intro, '');
    for (const name of g.tools) {
      const t = byName.get(name)!;
      const rest = restFor(name);
      out.push(
        `### \`${t.name}\``,
        '',
        `**${t.title}**. Scope: \`${t.scope}\`${hints(t.annotations)}.${rest.length ? ` REST: ${rest.join(', ')}.` : ''}`,
        '',
        cell(t.description),
        '',
        inputTable(t.input),
        ''
      );
    }
  }
  return out.join('\n');
}

