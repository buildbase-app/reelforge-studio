/** Optional engines: what they need, and what to use without them (from the engine plugins). */
const OPTIONAL_ENGINES = [remotionEngine()].filter((p) => p.requires);

function templateNeeds(id: string, engine: string): string {
  const p = OPTIONAL_ENGINES.find((e) => e.id === engine);
  if (!p) return '';
  const alt = p.alternatives?.[id];
  return ` **${p.requires}** (optional engine, not in the official image)${alt?.length ? `; without it use ${alt.map((a) => `\`${a}\``).join(' or ')}` : ''}.`;
}

