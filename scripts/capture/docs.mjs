// Writes the docs pages that show the captures, from the committed manifest
// (scripts/capture/assets.json), so a page always matches what was uploaded:
//   docs/public/screenshots/store.md   every store page, both themes and widths
//   docs/public/screenshots/studio.md  terminal views and template contact sheets
//   docs/public/walkthroughs.md        the walkthrough videos
// Pure rendering (renderStorePage & co.) plus one function that writes them.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { formatBytes, routeSlug } from './lib.mjs';
import { REPO_ROOT } from './run.mjs';
import { PROD_SITE, STORE_ROUTES, SIGNED_IN_ROUTES } from './targets.mjs';

export const VIDEO_BASE = `${PROD_SITE}/walkthroughs`;
const GENERATED = '<!-- GENERATED by scripts/capture from scripts/capture/assets.json. Do not edit; run `pnpm capture`. -->';
const WIDTHS = [390, 1440];
const THEMES = ['light', 'dark'];

const img = (e, alt) => (e?.url ? `![${alt}](${e.url})` : `_${alt}: not uploaded yet_`);
/** A fold crop that opens the full page. */
const thumb = (fold, full, alt) => (fold?.url ? (full?.url ? `[${img(fold, alt)}](${full.url})` : img(fold, alt)) : `_not captured_`);
const day = (entries) => entries.map((e) => e.capturedOn).filter(Boolean).sort().pop() ?? '';

function frontMatter({ title, description, slug, order, tags }) {
  return `---\ntitle: "${title}"\ndescription: "${description}"\nfolder: screenshots\nslug: ${slug}\norder: ${order}\ntags: [${tags.join(', ')}]\n---\n\n# ${title}\n\n${GENERATED}\n`;
}

function routeOrder(route) {
  const i = STORE_ROUTES.findIndex((r) => r.route === route);
  return i === -1 ? 999 : i;
}

/** docs/public/screenshots/store.md */
export function renderStorePage(manifest) {
  const all = Object.values(manifest.images ?? {});
  const get = (group, site, slug, width, theme, crop) => manifest.images[[group, site, slug, `${width}`, theme, crop].join('--')];
  const out = [
    frontMatter({
      title: 'Store screenshots',
      description: 'Every page of the ReelForge store at phone and desktop width, in light and dark, plus the signed-in pages after claiming and buying a licence on the test site. Licence keys and emails are masked.',
      slug: 'store-screenshots',
      order: 1,
      tags: ['screenshots'],
    }),
  ];
  const dev = all.filter((e) => e.group === 'store' && e.site === 'dev');
  const prod = all.filter((e) => e.group === 'store' && e.site === 'prod');
  const notes = [...new Map(dev.filter((e) => e.note).map((e) => [e.route, e.note])).entries()];
  out.push(`Every page of the store, captured by \`pnpm capture\` with Playwright's Chromium at 390 px (phone) and 1440 px (desktop) wide, light and dark, at twice the pixel density. Each image is the part above the fold; select it to open the full page. Motion is frozen for the stills and licence keys, emails and tokens are masked before a page is captured.

The test site is https://reelforge-dev.buildbase.app (BuildBase development environment, Stripe test mode); it runs the same build as production. Captured ${day(dev)}.
`);
  if (notes.length) {
    out.push(`**Empty states at capture time.** These pages are captured as they are and will be captured again (\`pnpm capture --only pages --upload\`) once their content is served:\n\n${notes.map(([route, note]) => `- \`${route}\`: ${note}`).join('\n')}\n`);
  }
  out.push('## Test site, every page\n');
  const routes = [...new Map(dev.map((e) => [e.route, e])).values()].sort((a, b) => routeOrder(a.route) - routeOrder(b.route));
  for (const r of routes) {
    out.push(`### ${r.title} (\`${r.route}\`)\n`);
    out.push('| | Phone (390 px) | Desktop (1440 px) |\n| --- | --- | --- |');
    for (const theme of THEMES) {
      const cells = WIDTHS.map((w) => thumb(get('store', 'dev', r.slug, w, theme, 'fold'), get('store', 'dev', r.slug, w, theme, 'full'), `${r.title}, ${theme}, ${w} px`));
      out.push(`| ${theme === 'light' ? 'Light' : 'Dark'} | ${cells.join(' | ')} |`);
    }
    if (r.note) out.push(`\n${r.status === 404 && r.route !== '/this-page-does-not-exist' ? 'Answered 404' : 'Empty state'}: ${r.note}.`);
    out.push('');
  }

  // Flows: the steps as seen in the recording, then the signed-in pages.
  const flows = [...new Set(all.filter((e) => e.group === 'flow').map((e) => e.flow))];
  if (flows.length) {
    out.push(`## Signed in on the test site\n\nTwo flows, each with a fresh \`+test\` account: claiming the free Personal licence, and buying the Studio tier of the Commercial licence with Stripe's test card 4242 4242 4242 4242. Both are also recorded as [walkthrough videos](/docs/screenshots/walkthroughs). Emails, passwords and licence keys are masked.\n`);
    for (const flow of flows) {
      const steps = all.filter((e) => e.group === 'flow' && e.flow === flow);
      out.push(`### ${flow === 'personal-claim' ? 'Claim a free Personal licence' : 'Buy a Commercial licence'}\n`);
      out.push(steps.map((e) => `${e.title}\n\n${img(e, e.title)}\n`).join('\n'));
      const pages = SIGNED_IN_ROUTES.map((r) => ({ r, slug: `${flow}-${r.slug ?? routeSlug(r.route)}` })).filter(({ slug }) => get('signed-in', 'dev', slug, 1440, 'light', 'fold') || get('signed-in', 'dev', slug, 390, 'light', 'fold'));
      if (pages.length) {
        out.push(`Signed-in pages of this account:\n`);
        for (const { r, slug } of pages) {
          out.push(`#### ${r.title}\n\n| | Phone (390 px) | Desktop (1440 px) |\n| --- | --- | --- |`);
          for (const theme of THEMES) {
            out.push(`| ${theme === 'light' ? 'Light' : 'Dark'} | ${WIDTHS.map((w) => thumb(get('signed-in', 'dev', slug, w, theme, 'fold'), get('signed-in', 'dev', slug, w, theme, 'full'), `${r.title}, ${theme}, ${w} px`)).join(' | ')} |`);
          }
          out.push('');
        }
      }
    }
  }

  if (prod.length) {
    out.push(`## Production, for comparison\n\nhttps://reelforge.buildbase.app in the light theme, captured ${day(prod)}.\n\n| Page | Phone (390 px) | Desktop (1440 px) |\n| --- | --- | --- |`);
    const proutes = [...new Map(prod.map((e) => [e.route, e])).values()].sort((a, b) => routeOrder(a.route) - routeOrder(b.route));
    for (const r of proutes) {
      out.push(`| ${r.title}${r.note ? ` (${r.status === 404 && r.route !== '/this-page-does-not-exist' ? '404' : 'empty'})` : ''} | ${WIDTHS.map((w) => thumb(get('store', 'prod', r.slug, w, 'light', 'fold'), get('store', 'prod', r.slug, w, 'light', 'full'), `${r.title}, production, ${w} px`)).join(' | ')} |`);
    }
    out.push('');
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/** docs/public/screenshots/studio.md */
export function renderStudioPage(manifest) {
  const studio = Object.values(manifest.images ?? {}).filter((e) => e.group === 'studio');
  const by = (slug) => studio.find((e) => e.slug === slug);
  const out = [
    frontMatter({
      title: 'Studio screenshots',
      description: 'ReelForge Studio has no GUI: real terminal sessions (API key, server start, claude mcp add, readiness, metrics, a render with progress), contact sheets of every built-in template, and an agent session over MCP.',
      slug: 'studio-screenshots',
      order: 2,
      tags: ['screenshots', 'mcp'],
    }),
  ];
  out.push(`ReelForge Studio is a server without a graphical interface: you drive it from a terminal, from an AI agent over MCP, or over REST. These views are real sessions against a studio started from the repository, captured by \`pnpm capture --only studio\` on ${day(studio)} and drawn as terminal pages. API keys and tokens are masked; the commands show \`$REELFORGE_KEY\` where the key goes.
`);
  const sessions = [
    ['keys-create', 'Create an API key'],
    ['server-start', 'Start the studio'],
    ['docker-compose-up', 'Start it with Docker Compose'],
    ['claude-mcp-add', 'Connect Claude Code over MCP'],
    ['readyz', 'Readiness'],
    ['metrics', 'Prometheus metrics'],
    ['render-progress', 'A render job and its progress'],
  ];
  out.push('## Terminal sessions\n');
  for (const [slug, heading] of sessions) {
    const e = by(slug);
    if (!e) continue;
    out.push(`### ${heading}\n\n${e.caption ? `${e.caption}\n\n` : ''}${img(e, e.title)}\n`);
  }
  const replay = by('agent-session-replay');
  if (replay) out.push(`## An agent makes a reel\n\nThe last frame of the replay of a recorded Claude Code session: prompt, tool calls and results on the left, the reel it rendered on the right. The whole session is a [walkthrough video](/docs/screenshots/walkthroughs).\n\n${img(replay, replay.title)}\n`);
  const sheets = studio.filter((e) => e.slug.startsWith('template-'));
  if (sheets.length) {
    out.push(`## Contact sheets of the built-in templates\n\nOne scene per template, rendered by its engine in the session above (\`scripts/capture/fixtures/contact-sheet-reel.json\`), with six frames spread over each scene. This is the review a template gets before it ships.\n`);
    for (const e of sheets) out.push(`### ${e.title}\n\n${e.caption ? `${e.caption}.\n\n` : ''}${img(e, `Contact sheet: ${e.title}`)}\n`);
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

/** docs/public/walkthroughs.md */
export function renderWalkthroughsPage(manifest) {
  const videos = Object.values(manifest.videos ?? {});
  const order = ['personal-claim', 'commercial-purchase', 'agents-copy-snippet', 'docs-navigation', 'gallery-browsing', 'agent-session', 'agent-session-vertical'];
  videos.sort((a, b) => order.indexOf(a.slug) - order.indexOf(b.slug));
  const out = [
    frontMatter({
      title: 'Walkthrough videos',
      description: 'Short recordings of whole processes in ReelForge: claiming a Personal licence, buying a Commercial licence, connecting Claude Code, and an agent making a reel over MCP.',
      slug: 'walkthroughs',
      order: 3,
      tags: ['screenshots', 'walkthroughs'],
    }),
  ];
  out.push(`Each video is a real run, recorded with Playwright by \`pnpm capture\` and cut to H.264 MP4 and WebM. The store flows run on the test site (https://reelforge-dev.buildbase.app: BuildBase development environment in test mode, Stripe test card); emails, passwords and licence keys are masked in every frame. Select a poster to play the MP4.
`);
  for (const v of videos) {
    const poster = manifest.images?.[v.posterKey];
    const mp4 = `${VIDEO_BASE}/${v.files.mp4.name}`;
    const webm = `${VIDEO_BASE}/${v.files.webm.name}`;
    out.push(`## ${v.title}\n`);
    out.push(`${poster?.url ? `[![${v.title}: poster](${poster.url})](${mp4})` : ''}\n`);
    out.push(`[MP4](${mp4}) (${formatBytes(v.files.mp4.bytes)}) · [WebM](${webm}) (${formatBytes(v.files.webm.bytes)}) · ${v.width}×${v.height} · ${Math.round(v.duration)} s${v.recordedOn ? ` · recorded ${v.recordedOn}` : ''}\n`);
    out.push(`**What it proves:** ${v.proves}\n`);
    out.push(`${v.steps.map((s, i) => `${i + 1}. ${s.text}`).join('\n')}\n`);
  }
  const missing = [
    ['docs-navigation', 'Docs navigation: recorded once the docs show content on the store (#93).'],
    ['gallery-browsing', 'Gallery browsing: recorded once the gallery shows its reels (served from R2, #89).'],
  ].filter(([slug]) => !videos.some((v) => v.slug === slug));
  if (missing.length) out.push(`## Still to record\n\n${missing.map(([, t]) => `- ${t}`).join('\n')}\n`);
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

export const PAGES = {
  'docs/public/screenshots/store.md': renderStorePage,
  'docs/public/screenshots/studio.md': renderStudioPage,
  'docs/public/walkthroughs.md': renderWalkthroughsPage,
};

/** Writes the pages that have content; returns their paths. */
export function writeDocsPages(manifest, root = REPO_ROOT) {
  const written = [];
  const has = {
    'docs/public/screenshots/store.md': Object.values(manifest.images ?? {}).some((e) => e.group === 'store'),
    'docs/public/screenshots/studio.md': Object.values(manifest.images ?? {}).some((e) => e.group === 'studio'),
    'docs/public/walkthroughs.md': Object.keys(manifest.videos ?? {}).length > 0,
  };
  for (const [path, render] of Object.entries(PAGES)) {
    if (!has[path]) continue;
    writeFileSync(join(root, path), render(manifest));
    written.push(path);
  }
  return written;
}
