// BuildBase console settings as code: nobody signs in to the console here.
// Reads the development environment's configuration (blueprint exports given
// with --blueprint, plus read-only GETs of the org API with the environment's
// token when one is set), redacts it, and renders the readable page
// out/console/buildbase-console-setup.md. The page and the redacted snapshot
// stay in out/ (never committed): it describes the store's own back end, which
// no customer needs.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { checkTokenEnvironment, readToken } from '../../docs/sync-buildbase.mjs';
import { redactConfig, stableJson } from '../lib.mjs';
import { REPO_ROOT } from '../run.mjs';

export const CONSOLE_PAGE = 'out/console/buildbase-console-setup.md';
const ENV_KEY = 'fsyqdskf';
/** Read-only org API routes the page is built from (GET only). */
export const READS = {
  authMethods: 'auth/methods',
  authClients: 'auth/settings',
  authPage: 'auth/configs',
  signupAccess: 'auth/signup-access',
  selling: 'marketplace/settings',
  goLive: 'marketplace/go-live',
  itemTypes: 'marketplace/item-types',
  ownStoreItems: 'marketplace/own-store/items',
  senderStatus: 'emails/senders/status',
  templates: 'emails/templates?$limit=200',
  docsFolders: 'docs/folders?$limit=200',
  docs: 'docs?$limit=1&draftPreview=true',
  blogs: 'blogs?$limit=1',
  collections: 'collections',
};

/** Merges blueprint objects: later files fill in what earlier ones lack. */
export function mergeBlueprints(list) {
  const merge = (a, b) => {
    if (a && b && typeof a === 'object' && typeof b === 'object' && !Array.isArray(a) && !Array.isArray(b)) {
      const out = { ...a };
      for (const [k, v] of Object.entries(b)) out[k] = k in out ? merge(out[k], v) : v;
      return out;
    }
    return a ?? b;
  };
  return list.reduce((acc, b) => merge(acc, b), {});
}

async function readLive(run) {
  const token = readToken();
  if (!token) {
    run.note('console: no BUILDBASE_API_TOKEN[_FILE]; the page is built from the blueprint files only');
    return {};
  }
  checkTokenEnvironment(token, ENV_KEY, process.env.BUILDBASE_ORG_ID);
  const base = (process.env.BUILDBASE_SERVER_URL || 'https://api.console.buildbase.app').replace(/\/$/, '');
  const out = {};
  for (const [name, path] of Object.entries(READS)) {
    const res = await fetch(`${base}/api/${path}`, { headers: { Authorization: `Bearer ${token}`, Accept: 'application/json', 'User-Agent': 'reelforge-capture' } });
    if (!res.ok) {
      run.note(`console: GET /api/${path.split('?')[0]} answered ${res.status}; that section is left out`);
      continue;
    }
    out[name] = await res.json();
  }
  return out;
}

// Markdown table cell: backslashes first, then pipes, then one line.
const cell = (v) => String(v ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n+/g, ' ');
const yes = (b) => (b ? 'yes' : 'no');
const money = (p) => (p.mode === 'free' ? 'Free' : `${(p.amount / 100).toFixed(2)} ${p.currency.toUpperCase()}`);
const table = (head, rows) =>
  rows.length
    ? `| ${head.join(' | ')} |\n| ${head.map(() => '---').join(' | ')} |\n${rows.map((r) => `| ${r.map((v, i) => cell(head[0] === 'Setting' && i === 1 && (v ?? '') === '' ? '(not set)' : v)).join(' | ')} |`).join('\n')}\n`
    : '_None._\n';
const docsOf = (x) => (Array.isArray(x) ? x : x?.docs ?? []);

/** The page, from the redacted blueprint and live snapshot. Pure. */
export function renderConsolePage({ blueprint: bp, live, date }) {
  const L = live ?? {};
  const out = [];
  out.push(`---
title: "BuildBase console setup"
description: "How the RenderWeld store is configured in BuildBase, read from the development environment as code: sign-in, selling and items, item type, webhooks, content and email, with secrets redacted."
folder: install
slug: buildbase-console-setup
order: 6
tags: [install, buildbase, reference]
---

# BuildBase console setup

<!-- GENERATED by scripts/capture (pnpm capture --only console). Do not edit; re-run it. -->

The RenderWeld store (reelforge.buildbase.app) runs on BuildBase: accounts and sign-in, the licence items and their prices, checkout, licence keys, webhooks, docs and blog content. This page is that configuration, read from the **development environment** (\`${ENV_KEY}\`, the test site reelforge-dev.buildbase.app, Stripe test keys) on ${date}, rather than screenshots of the console. Production has the same structure with live keys and its own URLs.

Secrets never appear: they are \`\${env:NAME}\` placeholders in the blueprint or shown as "[redacted]". The page is regenerated with \`pnpm capture --only console\` (docs/CAPTURE.md). The screens to photograph by hand, with their menu paths, are listed in [the console screenshot checklist](../../CONSOLE_SCREENSHOTS.md).
`);

  // Sign-in
  out.push('## Sign-in\n\nConsole: **Users** > **Authentication**.\n');
  const methods = docsOf(L.authMethods).length ? docsOf(L.authMethods).map((m) => [m.title, m.method]) : Object.entries(bp.auth?.methods ?? {}).map(([, m]) => [m.title, m.type]);
  out.push(`### Sign-in methods\n\n${table(['Method', 'Type'], methods)}`);
  const clients = docsOf(L.authClients).length ? docsOf(L.authClients) : Object.values(bp.auth?.clients ?? {});
  for (const c of clients) {
    out.push(`### Sign-in client "${c.title}"\n\n${table(['Setting', 'Value'], [
      ['Display name', c.branding?.displayName ?? c.title],
      ['Client ID (public, in the site build)', c.clientId ?? '(see the console)'],
      ['Kind', c.clientKind ?? c.type],
      ['Redirect URLs', (c.redirectUrls ?? []).join(', ')],
      ['Token URL', c.applicationTokenUrl],
      ['Profile URL', c.applicationProfileUrl],
      ['PKCE required', yes(c.requirePkce)],
      ['Device grant', yes(c.deviceGrant)],
      ['Client secret', '[redacted]'],
    ])}`);
  }
  const page = docsOf(L.authPage)[0];
  if (page) {
    out.push(`### Hosted sign-in page\n\n${table(['Setting', 'Value'], [
      ['Session length', `${page.security?.sessionTtlDays} days (remember me: ${yes(page.security?.allowRememberMe)}, ${page.security?.rememberMeDays} days)`],
      ['Block disposable email', yes(page.security?.blockDisposableEmail)],
      ['Two-factor', `${page.mfa?.enforcement} (${(page.mfa?.allowedFactors ?? []).join(', ')})`],
      ['Magic link in the same browser', yes(page.magicLinkSameBrowser)],
      ['Who may sign up', L.signupAccess?.mode ?? 'open'],
    ])}`);
  }
  if (bp.workspaces) {
    const w = bp.workspaces;
    out.push(`### Workspaces\n\n${table(['Setting', 'Value'], [
      ['Mode', w.mode],
      ['Workspaces per user', w.maxWorkspacesPerUser],
      ['Create the first one automatically', yes(w.autoCreateFirst)],
      ['Users can create or invite', `${yes(w.canCreateWorkspace)} / ${yes(w.canInviteMembers)}`],
    ])}\nEach buyer has one personal workspace; licences belong to the account.\n`);
  }

  // Selling
  out.push('## Selling and the own store\n\nConsole: **Billing** > **Selling** (tabs **Overview**, **Settings**, **Items**, **Orders**) and **Billing** > **Credentials**.\n');
  const s = L.selling;
  if (s) {
    out.push(`### Selling settings\n\n${table(['Setting', 'Value'], [
      ['Environment', `${s.environment?.name} (${s.livemode ? 'live' : 'Stripe test keys'})`],
      ['Shape', s.shape],
      ['Own store (the app owner sells)', `${yes(s.ownStore?.enabled)}, shown as "${s.ownStore?.displayName}"`],
      ['Buyers', s.buyers],
      ['Tax at checkout', s.taxMode],
      ['Item approval', s.approval],
      ['Platform country', s.platformCountry],
      ['Seller terms', s.terms?.sellerTermsUrl],
      ['Refund policy', s.terms?.refundPolicyUrl],
      ['Buyer terms (licence)', s.terms?.buyerTermsUrl],
      ['Privacy policy', s.terms?.privacyPolicyUrl],
    ])}`);
  }
  if (L.goLive?.checks) out.push(`### Go-live checklist (development)\n\n${table(['Check', 'Status', 'Detail'], L.goLive.checks.map((c) => [c.title, c.status, c.detail]))}`);
  const stripe = bp.billing?.stripe;
  if (stripe) {
    out.push(`### Stripe credentials\n\n${table(['Setting', 'Value'], [
      ['Publishable key', stripe.publishableKey ? `${String(stripe.publishableKey).slice(0, 8)}… (public, test mode)` : '(not exported)'],
      ['Secret key', stripe.secretKey ?? '[redacted]'],
      ['Webhook signing secret', stripe.webhookSecret ?? '[redacted]'],
    ])}`);
  }
  const types = docsOf(L.itemTypes);
  if (types.length) out.push(`### Item type\n\nConsole: **Billing** > **Item types**.\n\n${table(['Key', 'Name', 'Live version', 'What it allows'], types.map((t) => [t.key, t.name, t.liveVersion, (t.summary ?? []).join(', ')]))}`);
  const items = docsOf(L.ownStoreItems);
  for (const it of items.filter((i) => i.status !== 'archived')) {
    out.push(`### Item "${it.title}" (${it.status})\n\n${it.summary}\n\n${table(['Variant', 'Price', 'Benefits'], it.variants.map((v) => [v.label, (v.prices ?? []).map(money).join(', '), (v.benefitIds ?? []).map((id) => {
      const b = it.benefits.find((x) => x.id === id);
      return b ? `${b.title}${b.activationLimit ? ` (${b.activationLimit} activation${b.activationLimit > 1 ? 's' : ''})` : ''}` : id;
    }).join('; ')]))}`);
  }
  if (items.some((i) => i.status === 'archived')) out.push(`Archived items (kept for past orders): ${items.filter((i) => i.status === 'archived').map((i) => `"${i.title}"`).join(', ')}.\n`);

  // Webhooks
  out.push('## Webhooks\n\nConsole: **Settings** > **Webhooks**. BuildBase signs each delivery; the store checks the signature with the endpoint\'s secret (stored as a Worker secret, never here).\n');
  out.push(table(['Name', 'URL', 'Events', 'Enabled', 'Signing secret'], Object.values(bp.webhooks ?? {}).map((w) => [w.name, w.url, (w.events ?? []).join(', '), yes(w.enabled ?? true), '[redacted]'])));

  // Content
  out.push('\n## Content\n\nConsole: **Content** > **Docs**, **Content** > **Blogs** and **Content** > **Collections** (under **Data**).\n');
  const folders = docsOf(L.docsFolders);
  if (folders.length) out.push(`### Docs\n\n${L.docs?.totalDocs ?? '?'} doc pages (drafts included) in ${folders.length} folders: ${folders.map((f) => `${f.name} (\`${f.slug}\`)`).reverse().join(', ')}. The repository publishes them (docs/DOCS_PUBLISHING.md).\n`);
  if (L.blogs) out.push(`### Blog\n\n${L.blogs.totalDocs} published posts.\n`);
  for (const [slug, c] of Object.entries(bp.data?.collections ?? {})) {
    out.push(`### Collection "${c.name}" (\`${slug}\`)\n\n${table(['Field', 'Type', 'Required', 'Help'], (c.fields ?? []).map((f) => [f.slug, f.type, yes(f.required), f.helpText ?? '']))}`);
  }
  if (bp.data?.storage) out.push(`End-user uploads: ${yes(bp.data.storage.endUserUploads?.enabled)}, up to ${Math.round((bp.data.storage.endUserUploads?.maxFileBytes ?? 0) / 1048576)} MB a file.\n`);

  // Email
  out.push('\n## Email\n\nConsole: **Messaging** > **Sender accounts** (and **Messaging** > **Templates**).\n');
  const rows = [];
  if (L.senderStatus) rows.push(['A usable default sender', yes(L.senderStatus.hasUsableDefaultSender)]);
  const tpl = docsOf(L.templates);
  if (tpl.length) {
    const byCat = {};
    for (const t of tpl) byCat[t.category ?? 'other'] = (byCat[t.category ?? 'other'] ?? 0) + 1;
    rows.push(['Email templates', Object.entries(byCat).map(([k, n]) => `${n} ${k}`).join(', ')]);
  }
  const wl = bp.auth?.waitlist;
  if (wl) rows.push(['Waitlist emails (registered, approved, rejected)', ['registered', 'approved', 'rejected'].map((k) => (wl.emails?.[k]?.send ? 'sent' : 'off')).join(', ')]);
  out.push(table(['Setting', 'Value'], rows));
  out.push('\nIn the development environment sign-up runs in test mode: no mail is sent and the verification code is always 424242, which is how the walkthrough videos sign up.\n');
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

export async function captureConsole(run) {
  const files = (run.args.blueprint ?? join(run.out, 'inputs', 'dev-mcp-export.blueprint.json') + ',' + join(run.out, 'inputs', 'dev-auth-billing.blueprint.json')).split(',').map((f) => resolve(f));
  const present = files.filter((f) => existsSync(f));
  if (run.args.dryRun) {
    run.log(`console: would read ${present.length} blueprint file(s) and ${Object.keys(READS).length} read-only org API routes, and write ${CONSOLE_PAGE}`);
    return;
  }
  if (!present.length) {
    run.skip('console page', 'no blueprint file (export one with the BuildBase MCP blueprint_export, pass --blueprint <file>)');
    return;
  }
  const blueprint = redactConfig(mergeBlueprints(present.map((f) => JSON.parse(readFileSync(f, 'utf8')))));
  const live = redactConfig(await readLive(run));
  writeFileSync(join(run.out, 'console-snapshot.json'), stableJson({ blueprint, live }));
  mkdirSync(dirname(join(REPO_ROOT, CONSOLE_PAGE)), { recursive: true });
  writeFileSync(join(REPO_ROOT, CONSOLE_PAGE), renderConsolePage({ blueprint, live, date: new Date().toISOString().slice(0, 10) }));
  run.log(`console: wrote ${CONSOLE_PAGE} from ${present.length} blueprint file(s) and ${Object.keys(live).length} live reads`);
}
