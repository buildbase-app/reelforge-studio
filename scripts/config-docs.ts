/**
 * Writes docs/CONFIG.md from the configuration schema
 * (packages/core/src/config/schema.ts), so the reference never drifts.
 *
 *   pnpm docs:config           write docs/CONFIG.md
 *   pnpm docs:config --check   fail if docs/CONFIG.md is out of date (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETTINGS, type SettingDef } from '@reelforge/core';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'CONFIG.md');
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function defaultText(d: SettingDef): string {
  if (d.defaultText) return d.defaultText;
  if (d.default === undefined) return '(none)';
  if (Array.isArray(d.default)) return d.default.length ? `\`${d.default.join(',')}\`` : '(empty)';
  return `\`${String(d.default)}\``;
}

function envText(d: SettingDef): string {
  const names = [d.env, ...(d.aliases ?? [])].map((n) => `\`${n}\``);
  const text = names.join(', ');
  return d.secret ? `${text} (each also as \`_FILE\`)` : text;
}

function typeText(d: SettingDef): string {
  if (d.kind === 'enum') {
    const opts = (d.schema as unknown as { options?: string[] }).options;
    return opts ? opts.map((o) => `\`${o}\``).join(' \\| ') : 'enum';
  }
  return d.kind === 'list' ? 'list (comma-separated in env)' : d.kind;
}

const groups = new Map<string, SettingDef[]>();
for (const d of SETTINGS) {
  const g = d.key.split('.')[0]!;
  groups.set(g, [...(groups.get(g) ?? []), d]);
}

const lines: string[] = [
  '# Configuration reference',
  '',
  '<!-- GENERATED by scripts/config-docs.ts from packages/core/src/config/schema.ts. Do not edit; run `pnpm docs:config`. -->',
  '',
  'Every ReelForge Studio setting, generated from the one configuration schema.',
  'Precedence, lowest to highest (D-029):',
  '',
  '1. **default** (below)',
  '2. **file**: the YAML or JSON file named by `REELFORGE_CONFIG`, nested by key',
  '   (`limits.rateLimitPerMinute` is `limits: { rateLimitPerMinute: 120 }`); unknown keys are refused',
  '3. **env**: the environment variables below; the `REELFORGE_` name wins over older aliases;',
  '   every secret can also be read from a file named by `<NAME>_FILE` (Docker/Kubernetes secrets)',
  '4. **runtime**: values set over the API (`PATCH /v1/config`, MCP `update_config`, admin scope), stored in the',
  '   database; only settings with scope **runtime**. `null` clears a runtime value.',
  '',
  '**Release images** (the published Docker image, D-039) fix `licence.mode` (`required`), `licence.serverUrl` and',
  '`licence.orgId` at build time: their source is **build**, and a config file, environment variable or',
  '`update_config` that tries to change them is refused (`build_locked_setting`). Builds from source (`pnpm dev`,',
  '`--build-arg REELFORGE_EDITION=dev`) keep every setting configurable; `licence.mode: off` there is for',
  'noncommercial development only (LICENSING.md).',
  '',
  'Scope **startup** settings are read once at start; changing them at runtime is refused with an error that says',
  'where to set them. `GET /v1/config` / MCP `get_config` show each effective value and its source; secrets show',
  'only `set` / `not set`. Secrets set at runtime are stored encrypted (AES-256-GCM) with `REELFORGE_SECRET_KEY`;',
  'without it the server refuses to store them. Check a configuration without starting the server:',
  '`reelforge config check [--file PATH]`; print the effective one: `reelforge config show`.',
  '',
  'Example `reelforge.yaml`:',
  '',
  '```yaml',
  'server:',
  '  publicUrl: https://studio.example.com',
  'limits:',
  '  rateLimitPerMinute: 120',
  '  renderConcurrency: 2',
  'logging:',
  '  level: info',
  '```',
  '',
];

for (const [group, defs] of groups) {
  lines.push(`## ${group}`, '', '| Key | Env | Type | Default | Scope | Secret | Description |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const d of defs) {
    const desc = `${d.description}${d.placeholder ? ` _(Reserved for ${d.placeholder}.)_` : ''}${d.example ? ` Example: \`${d.example}\`.` : ''}`;
    lines.push(`| \`${d.key}\` | ${envText(d)} | ${typeText(d)} | ${cell(defaultText(d))} | ${d.scope} | ${d.secret ? 'yes' : ''} | ${cell(desc)} |`);
  }
  lines.push('');
}

lines.push(
  '## Not in the schema',
  '',
  '| Env | Description |',
  '| --- | --- |',
  '| `REELFORGE_CONFIG` | Path of the config file (YAML or JSON). |',
  '| Provider settings declared by plugins | Set with `configure_provider` / `PUT /v1/providers/:id/config` (stored encrypted, like `providers.*`) or the environment variable the provider names. |',
  '| `HYPERFRAMES_NO_TELEMETRY`, `DO_NOT_TRACK`, `CHECKPOINT_DISABLE` | Telemetry opt-outs for third-party tools, set in the Docker image. |',
  ''
);

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    // missing
  }
  if (current !== text) {
    console.error('docs/CONFIG.md is out of date with the configuration schema; run `pnpm docs:config` and commit it');
    process.exit(1);
  }
  console.log('docs/CONFIG.md is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${SETTINGS.length} settings)`);
}
