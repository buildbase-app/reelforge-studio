/**
 * `pnpm gallery report`: writes examples/gallery/QUALITY.md from the last
 * run: how many reels were rendered, passed the automated gate and the
 * contact-sheet review, which were rejected and why (<out>/rejected.json,
 * written by the reviewer), sizes after transcoding, render times, and the
 * split by engine and category.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { GalleryEntry } from './catalog/build';
import type { Meta } from './render';
import { readMedia } from './transcode';

function read<T>(f: string, fallback: T): T {
  return existsSync(f) ? (JSON.parse(readFileSync(f, 'utf8')) as T) : fallback;
}

const kb = (b: number) => `${Math.round(b / 1024)} KB`;

export function buildReport(outDir: string, entries: GalleryEntry[], notes = ''): string {
  const quality = read<{ results: { slug: string; ok: boolean; problems: string[] }[] }>(join(outDir, 'quality.json'), { results: [] });
  const rejected = read<Record<string, string>>(join(outDir, 'rejected.json'), {});
  const media = readMedia(outDir);
  const metas: Meta[] = entries.map((e) => join(outDir, e.gallery.slug, 'meta.json')).filter(existsSync).map((f) => JSON.parse(readFileSync(f, 'utf8')));
  const autoFail = quality.results.filter((r) => !r.ok && r.problems[0] !== 'not rendered');
  const accepted = entries.filter((e) => media[e.gallery.slug] && !rejected[e.gallery.slug]);
  const byEngine = new Map<string, { total: number; ok: number }>();
  const byCat = new Map<string, { total: number; ok: number }>();
  for (const e of entries) {
    const ok = accepted.includes(e);
    for (const en of e.gallery.engines) {
      const v = byEngine.get(en) ?? { total: 0, ok: 0 };
      v.total++;
      if (ok) v.ok++;
      byEngine.set(en, v);
    }
    const c = byCat.get(e.gallery.category) ?? { total: 0, ok: 0 };
    c.total++;
    if (ok) c.ok++;
    byCat.set(e.gallery.category, c);
  }
  const mp4 = accepted.map((e) => media[e.gallery.slug]!.mp4.bytes);
  const webm = accepted.map((e) => media[e.gallery.slug]!.webm.bytes);
  const over = accepted.filter((e) => media[e.gallery.slug]!.mp4.bytes > media[e.gallery.slug]!.budgetBytes);
  const renderTotal = metas.reduce((a, m) => a + m.renderSeconds, 0);
  const videoTotal = metas.reduce((a, m) => a + m.durationSeconds, 0);
  const hw = metas[0]?.hardware;
  const lines = [
    '# Gallery quality report',
    '',
    `Generated by \`pnpm gallery report\` on ${new Date().toISOString().slice(0, 10)} from the last render (see docs/GALLERY.md).`,
    '',
    '| | Reels |',
    '| --- | ---: |',
    `| In the catalog | ${entries.length} |`,
    `| Rendered | ${metas.length} |`,
    `| Failed the automated gate | ${autoFail.length} |`,
    `| Rejected in the contact-sheet review | ${Object.keys(rejected).length} |`,
    `| Accepted and transcoded | ${accepted.length} |`,
    '',
    `Render time: ${(renderTotal / 3600).toFixed(2)} h of studio wall clock for ${(videoTotal / 60).toFixed(1)} min of video` +
      (hw ? ` on ${hw.cpu}, ${hw.cores} cores, ${hw.ramGb} GB RAM (shared with other jobs while it ran)` : '') +
      (metas.length ? `; median ${median(metas.map((m) => m.renderSeconds)).toFixed(0)} s per reel.` : '.'),
    '',
    mp4.length
      ? `Web sizes (720x1280, no audio): MP4 median ${kb(median(mp4))}, max ${kb(Math.max(...mp4))}; WebM median ${kb(median(webm))}, max ${kb(Math.max(...webm))}. Over budget: ${over.length}.`
      : '',
    '',
    '## By engine',
    '',
    '| Engine | Reels using it | Accepted |',
    '| --- | ---: | ---: |',
    ...[...byEngine].map(([k, v]) => `| ${k} | ${v.total} | ${v.ok} |`),
    '',
    '## By category',
    '',
    '| Category | Reels | Accepted |',
    '| --- | ---: | ---: |',
    ...[...byCat].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => `| ${k} | ${v.total} | ${v.ok} |`),
    '',
    '## Rejected or failed',
    '',
    ...(autoFail.length || Object.keys(rejected).length
      ? [
          '| Reel | Why |',
          '| --- | --- |',
          ...autoFail.map((r) => `| ${r.slug} | automated gate: ${r.problems.join('; ')} |`),
          ...Object.entries(rejected).map(([s, why]) => `| ${s} | review: ${why} |`),
        ]
      : ['None.']),
    '',
    ...(notes ? ['## Review notes', '', notes.trim(), ''] : []),
  ];
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

function median(xs: number[]): number {
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length ? (s.length % 2 ? s[m]! : (s[m - 1]! + s[m]!) / 2) : 0;
}

export function writeReport(outDir: string, entries: GalleryEntry[], file: string): void {
  const notesFile = join(outDir, 'review-notes.md');
  writeFileSync(file, buildReport(outDir, entries, existsSync(notesFile) ? readFileSync(notesFile, 'utf8') : ''));
}
